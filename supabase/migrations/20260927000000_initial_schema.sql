create extension if not exists pgcrypto with schema extensions;

create table if not exists public.archive_category (
  id uuid primary key default gen_random_uuid(),
  name varchar(255) not null,
  description varchar(255),
  lang varchar(255) not null,
  category_code integer not null,
  unique (category_code, lang)
);

create table if not exists public.article (
  id uuid primary key default gen_random_uuid(),
  name varchar(255) not null,
  parent_articles varchar(255),
  description varchar(255),
  text varchar(255) not null,
  author varchar(255),
  creation_date varchar(255),
  lang varchar(255) not null,
  article_code integer not null,
  unique (article_code, lang)
);

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  code varchar(255) not null,
  floor smallint not null default 1,
  danger_type varchar(255),
  size varchar(255) default '2x2',
  color varchar(255) default 'RED',
  light_level smallint default 1,
  date date not null default current_date,
  status varchar(32)
);
create index if not exists idx_room_code on public.rooms(code);
create index if not exists idx_rooms_date_id on public.rooms(date desc, id desc);

create table if not exists public.room_translations (
  id uuid primary key default gen_random_uuid(),
  lang varchar(5) not null default 'ru-RU',
  name varchar(500) not null,
  description text not null,
  room_id uuid not null references public.rooms(id) on delete cascade,
  unique (room_id, lang)
);
create index if not exists idx_room_translations_lang on public.room_translations(lang);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  title varchar(255) not null,
  text text not null,
  post_date date not null default current_date,
  tags text[] not null default '{}',
  pinned boolean not null default false
);

create table if not exists public.story_category (
  id integer generated by default as identity primary key,
  title varchar(255),
  lang varchar(255)
);

create table if not exists public.stories (
  id uuid primary key default gen_random_uuid(),
  title varchar(255) not null,
  text text not null,
  date date default current_date,
  reading_time integer default 2,
  category integer not null references public.story_category(id),
  lang varchar(255),
  "order" integer not null default 0
);

create table if not exists public.album (
  id uuid primary key default gen_random_uuid(),
  title text,
  description text,
  description_ru text,
  cover_link text
);

create table if not exists public.track (
  id uuid primary key default gen_random_uuid(),
  link text,
  description text,
  description_ru text,
  "order" integer not null default 0,
  album_id uuid not null references public.album(id) on delete cascade
);

create table if not exists public.donations (
  id uuid primary key default gen_random_uuid(),
  amount real not null default 0,
  name text,
  message text
);

create table if not exists public.donation_goals (
  id uuid primary key default gen_random_uuid(),
  title text,
  title_ru text,
  target_amount real not null default 0,
  current_amount real not null default 0,
  active boolean not null default false
);

alter table public.archive_category enable row level security;
alter table public.article enable row level security;
alter table public.rooms enable row level security;
alter table public.room_translations enable row level security;
alter table public.posts enable row level security;
alter table public.story_category enable row level security;
alter table public.stories enable row level security;
alter table public.album enable row level security;
alter table public.track enable row level security;
alter table public.donations enable row level security;
alter table public.donation_goals enable row level security;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'archive_category','article','rooms','room_translations','posts',
    'story_category','stories','album','track'
  ]
  loop
    execute format('drop policy if exists "Public read" on public.%I', table_name);
    execute format('create policy "Public read" on public.%I for select to anon, authenticated using (true)', table_name);
    execute format('grant select on public.%I to anon, authenticated', table_name);
  end loop;
end $$;

create policy "Public reads active donation goal"
  on public.donation_goals for select to anon, authenticated using (active);
grant select on public.donation_goals to anon, authenticated;

create unique index if not exists one_active_donation_goal
  on public.donation_goals(active) where active;

create or replace function public.record_kofi_donation(
  p_amount real, p_name text, p_message text
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_goal_id uuid;
begin
  select id into current_goal_id
  from public.donation_goals
  where active = true
  for update;

  if current_goal_id is null then
    raise exception 'No active donation goal';
  end if;

  insert into public.donations(amount, name, message)
  values (p_amount, p_name, p_message);

  update public.donation_goals
  set current_amount = current_amount + p_amount
  where id = current_goal_id;
end;
$$;

revoke all on function public.record_kofi_donation(real, text, text) from public, anon, authenticated;
grant execute on function public.record_kofi_donation(real, text, text) to service_role;
